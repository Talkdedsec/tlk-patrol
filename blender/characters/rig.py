"""Humanoid rig definition, forward kinematics and two-bone IK helpers.

Runs inside Blender (mathutils). Axes: X = character right, Y = forward, Z = up (feet at z = 0).
Pose rotations ("D") are 3x3 matrices expressed in armature axes and applied hierarchically:
world rotation of a bone = D(parent chain) @ D(bone) @ B_rest(bone).
"""
import math
from mathutils import Matrix, Vector, Euler

I3 = Matrix.Identity(3)
MIRROR = Matrix.Diagonal((-1.0, 1.0, 1.0))


def rot(x=0.0, y=0.0, z=0.0):
    """Euler XYZ (degrees) -> 3x3 matrix in armature axes (X applied first, Z last)."""
    return Euler((math.radians(x), math.radians(y), math.radians(z)), "XYZ").to_matrix()


def mir(m):
    return MIRROR @ m @ MIRROR


# --- skeleton ------------------------------------------------------------------------------------
# name, parent, head, tail. Right side is +X; left side is generated by mirroring.
_CENTER = [
    ("Hips", None, (0, 0, 0.93), (0, 0, 1.03)),
    ("Spine", "Hips", (0, 0, 1.03), (0, 0, 1.18)),
    ("Chest", "Spine", (0, 0, 1.18), (0, 0, 1.44)),
    ("Neck", "Chest", (0, 0, 1.44), (0, 0, 1.54)),
    ("Head", "Neck", (0, 0, 1.54), (0, 0, 1.78)),
    ("Socket_Back", "Chest", (0, -0.15, 1.30), (0, -0.15, 1.40)),
    ("Socket_CuffBack", "Hips", (0, -0.13, 0.99), (0, -0.13, 1.04)),
]
_SIDE = [
    ("Shoulder_R", "Chest", (0.04, 0, 1.40), (0.19, 0, 1.41)),
    ("UpperArm_R", "Shoulder_R", (0.235, 0, 1.40), (0.235, 0, 1.12)),
    ("LowerArm_R", "UpperArm_R", (0.235, 0, 1.12), (0.235, 0, 0.87)),
    ("Hand_R", "LowerArm_R", (0.235, 0, 0.87), (0.235, 0, 0.77)),
    ("Socket_Hand_R", "Hand_R", (0.235, 0.0, 0.82), (0.235, 0.0, 0.77)),
    ("UpperLeg_R", "Hips", (0.095, 0, 0.93), (0.095, 0, 0.50)),
    ("LowerLeg_R", "UpperLeg_R", (0.095, 0, 0.50), (0.095, 0, 0.08)),
    ("Foot_R", "LowerLeg_R", (0.095, 0, 0.08), (0.095, 0.14, 0.03)),
    ("Socket_Holster_R", "Hips", (0.215, 0.0, 0.92), (0.215, 0.0, 0.84)),
]
BONES = list(_CENTER)
for _n, _p, _h, _t in _SIDE:
    BONES.append((_n, _p, _h, _t))
    BONES.append((
        _n.replace("_R", "_L"),
        _p.replace("_R", "_L") if _p else None,
        (-_h[0], _h[1], _h[2]),
        (-_t[0], _t[1], _t[2]),
    ))
# left belt socket (flashlight / taser) has no right twin
BONES.append(("Socket_Belt_L", "Hips", (-0.215, 0.0, 0.92), (-0.215, 0.0, 0.84)))

NAMES = [b[0] for b in BONES]
PARENT = {b[0]: b[1] for b in BONES}
HEAD = {b[0]: Vector(b[2]) for b in BONES}
TAIL = {b[0]: Vector(b[3]) for b in BONES}

UPPER_BODY = [
    "Spine", "Chest", "Neck", "Head",
    "Shoulder_R", "UpperArm_R", "LowerArm_R", "Hand_R",
    "Shoulder_L", "UpperArm_L", "LowerArm_L", "Hand_L",
]
LOWER_BODY = ["Hips", "UpperLeg_R", "LowerLeg_R", "Foot_R", "UpperLeg_L", "LowerLeg_L", "Foot_L"]
DEFORM = UPPER_BODY + LOWER_BODY

# filled once the armature exists (bone rest matrices come from Blender)
B_REST = {}


def create_armature(bpy):
    """Build the armature object, fill B_REST. Returns the armature object."""
    arm_data = bpy.data.armatures.new("Armature")
    obj = bpy.data.objects.new("Armature", arm_data)
    bpy.context.scene.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.mode_set(mode="EDIT")
    edit = {}
    for name, parent, head, tail in BONES:
        eb = arm_data.edit_bones.new(name)
        eb.head = head
        eb.tail = tail
        eb.roll = 0.0
        edit[name] = eb
    for name, parent, _h, _t in BONES:
        if parent:
            edit[name].parent = edit[parent]
    bpy.ops.object.mode_set(mode="OBJECT")
    for name in NAMES:
        B_REST[name] = arm_data.bones[name].matrix_local.to_3x3().copy()
    return obj


# --- forward kinematics ---------------------------------------------------------------------------
def fk(d, loc=None):
    """d: bone -> D matrix (missing = identity). loc: bone -> Vector offset (armature axes, root bone).
    Returns (pos, acc): posed head positions and accumulated rotations (parents' D incl. own)."""
    pos, acc = {}, {}
    for name in NAMES:
        parent = PARENT[name]
        dm = d.get(name, I3)
        if parent is None:
            pos[name] = HEAD[name] + (Vector(loc[name]) if loc and name in loc else Vector())
            acc[name] = dm
        else:
            pos[name] = pos[parent] + acc[parent] @ (HEAD[name] - HEAD[parent])
            acc[name] = acc[parent] @ dm
    return pos, acc


def frame_from(f, up):
    """Desired world frame of a hand/foot bone (bone Y along f, bone Z along `up`)."""
    f = Vector(f).normalized()
    z = Vector(up)
    z = (z - f * z.dot(f)).normalized()
    x = f.cross(z)
    return Matrix(((x.x, f.x, z.x), (x.y, f.y, z.y), (x.z, f.z, z.z)))


def ik_limb(d, loc, root, mid, end, target, hint, sign, end_frame=None):
    """Two-bone IK for hanging-at-rest limbs (bones point -Z at rest).
    target: world position of `end` bone head. hint: direction the middle joint bulges to.
    sign: +1 for arms (elbow flexes with +X), -1 for legs (knee flexes with -X).
    end_frame: optional world frame (see frame_from) for the end bone. Writes into d."""
    pos, acc = fk(d, loc)
    parent = PARENT[root]
    s = pos[root]
    l1 = (HEAD[mid] - HEAD[root]).length
    l2 = (HEAD[end] - HEAD[mid]).length
    t = Vector(target)
    v = t - s
    dist = v.length
    dist = min(max(dist, abs(l1 - l2) + 0.01), l1 + l2 - 0.002)
    dirn = v.normalized()
    a = (l1 * l1 - l2 * l2 + dist * dist) / (2.0 * dist)
    h = math.sqrt(max(l1 * l1 - a * a, 0.0))
    hint_v = Vector(hint)
    perp = hint_v - dirn * hint_v.dot(dirn)
    if perp.length < 1e-5:
        perp = Vector((0, 0, -1)).cross(dirn)
    perp.normalize()
    elbow = s + dirn * a + perp * h
    u = (elbow - s).normalized()
    f = (s + dirn * dist - elbow).normalized()
    cross = u.cross(f)
    phi = math.acos(max(-1.0, min(1.0, u.dot(f))))
    if cross.length < 1e-6:
        cross = Vector((1, 0, 0))
    hinge = cross.normalized() * sign
    zp = -u
    yp = zp.cross(hinge)
    d1 = Matrix(((hinge.x, yp.x, zp.x), (hinge.y, yp.y, zp.y), (hinge.z, yp.z, zp.z)))
    d[root] = acc[parent].inverted() @ d1
    d2 = rot(x=math.degrees(phi) * sign)
    d[mid] = d2
    if end_frame is not None:
        world = end_frame @ B_REST[end].inverted()
        d[end] = (d1 @ d2).inverted() @ world
    return d


# --- conversions ----------------------------------------------------------------------------------
def basis_quaternion(bone, dm):
    """Pose-bone local rotation for a D expressed in armature axes."""
    b = B_REST[bone]
    return (b.inverted() @ dm @ b).to_quaternion()


def basis_location(bone, vec):
    return B_REST[bone].inverted() @ Vector(vec)
